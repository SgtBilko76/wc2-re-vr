#!/usr/bin/env python3
"""Render the VR on-screen keyboard used for pilot names / callsigns / saves.

Outputs:
  quest/android/app/src/main/assets/keyboard.rgba.z   zlib-compressed RGBA
  src/quest/quest_keyboard_layout.h                   key rectangles + codes

ReadTextInput (trainsim.c) accepts A-Z, 0-9 and space, Backspace, Enter and
Escape, so the layout carries exactly those keys.
"""
import pathlib
import zlib

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
ASSET = ROOT / "quest/android/app/src/main/assets/keyboard.rgba.z"
HEADER = ROOT / "src/quest/quest_keyboard_layout.h"
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

UNIT = 84
GAP = 8
KEY_H = 80
MARGIN = 14

# (label, SDL keycode expression, width in units)
ROWS = [
    (0.0, [(c, f"'{c.lower()}'", 1) for c in "1234567890"] +
          [("Back", "SDLK_BACKSPACE", 1.5)]),
    (0.25, [(c, f"'{c.lower()}'", 1) for c in "QWERTYUIOP"]),
    (0.5, [(c, f"'{c.lower()}'", 1) for c in "ASDFGHJKL"] +
          [("Enter", "SDLK_RETURN", 1.75)]),
    (0.0, [("Shift", "SDLK_LSHIFT", 1.25)] +
          [(c, f"'{c.lower()}'", 1) for c in "ZXCVBNM"] +
          [("Space", "SDLK_SPACE", 1.75), ("Cancel", "SDLK_ESCAPE", 1.5)]),
]


def layout():
    keys = []
    width = 0
    for row, (offset, row_keys) in enumerate(ROWS):
        x = MARGIN + offset * (UNIT + GAP)
        y = MARGIN + row * (KEY_H + GAP)
        for label, code, units in row_keys:
            w = units * UNIT + (units - 1) * GAP
            keys.append((label, code, int(x), int(y), int(x + w), int(y + KEY_H)))
            x += w + GAP
        width = max(width, x - GAP + MARGIN)
    height = MARGIN * 2 + len(ROWS) * KEY_H + (len(ROWS) - 1) * GAP
    return keys, int(width + 3) & ~3, height


def main():
    keys, width, height = layout()
    image = Image.new("RGBA", (width, height), (12, 16, 28, 235))
    draw = ImageDraw.Draw(image)
    big = ImageFont.truetype(FONT, 40)
    small = ImageFont.truetype(FONT, 28)
    for label, code, x0, y0, x1, y1 in keys:
        special = len(label) > 1
        fill = (52, 64, 92, 255) if special else (70, 78, 98, 255)
        draw.rounded_rectangle((x0, y0, x1, y1), radius=10, fill=fill,
                               outline=(130, 150, 190, 255), width=2)
        font = small if special else big
        box = draw.textbbox((0, 0), label, font=font)
        tx = (x0 + x1) / 2 - (box[2] - box[0]) / 2 - box[0]
        ty = (y0 + y1) / 2 - (box[3] - box[1]) / 2 - box[1]
        draw.text((tx, ty), label, font=font, fill=(235, 240, 255, 255))

    # Premultiply alpha: the XR quad is composited with SOURCE_ALPHA.
    pixels = bytearray(image.tobytes())
    for i in range(0, len(pixels), 4):
        a = pixels[i + 3]
        if a != 255:
            pixels[i] = pixels[i] * a // 255
            pixels[i + 1] = pixels[i + 1] * a // 255
            pixels[i + 2] = pixels[i + 2] * a // 255

    ASSET.parent.mkdir(parents=True, exist_ok=True)
    ASSET.write_bytes(zlib.compress(bytes(pixels), 9))
    image.save(ROOT / "quest/tools/keyboard_preview.png")

    lines = [
        "/* Generated by quest/tools/gen_keyboard.py - do not edit. */",
        "#ifndef WC2_QUEST_KEYBOARD_LAYOUT_H",
        "#define WC2_QUEST_KEYBOARD_LAYOUT_H",
        "#include \"SDL_keycode.h\"",
        f"#define QUEST_KEYBOARD_WIDTH {width}",
        f"#define QUEST_KEYBOARD_HEIGHT {height}",
        f"#define QUEST_KEYBOARD_KEY_COUNT {len(keys)}",
        "typedef struct QuestKeyboardKey {",
        "    int keycode;",
        "    short x0, y0, x1, y1;",
        "} QuestKeyboardKey;",
        "static const QuestKeyboardKey g_questKeyboardKeys[] = {",
    ]
    for label, code, x0, y0, x1, y1 in keys:
        lines.append(f"    {{ {code}, {x0}, {y0}, {x1}, {y1} }}, /* {label} */")
    lines += ["};", "#endif", ""]
    HEADER.write_text("\n".join(lines))
    print(f"keyboard {width}x{height}, {len(keys)} keys, "
          f"{ASSET.stat().st_size} bytes compressed")


if __name__ == "__main__":
    main()
